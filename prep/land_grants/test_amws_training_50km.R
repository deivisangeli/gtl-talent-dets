# Run with Rscript from the repository root; no dataset mutation.
args <- commandArgs(trailingOnly = FALSE)
f <- sub("^--file=", "", args[grepl("^--file=", args)][1])
if (is.na(f)) f <- file.path("prep", "land_grants", "test_amws_training_50km.R")
source(file.path(dirname(normalizePath(f, winslash = "/")), "amws_training_helpers.R"))

stopifnot(training_classify(50000, 1L, TRUE) == "ever_nearby")
stopifnot(training_classify(50000.0001, 1L, TRUE) == "never_nearby")
stopifnot(training_classify(c(70000, 10000), 1L, TRUE) == "ever_nearby")
stopifnot(training_classify(c(10000, NA), 2L, c(TRUE, FALSE)) == "ever_nearby")
stopifnot(training_classify(70000, 2L, c(TRUE, FALSE)) == "unknown")
stopifnot(training_classify(numeric(), 0L, logical()) == "unknown")
stopifnot(training_classify(numeric(), 1L, FALSE) == "unknown")
stopifnot(training_classify(70000, 1L, FALSE) == "unknown")
stopifnot(training_classify(70000, 1L, TRUE, TRUE) == "unknown")
stopifnot(training_classify(c(70000, 80000), 2L, c(TRUE, TRUE)) == "never_nearby")
# Graduation-year completeness is deliberately not an argument: known unconditional locations remain usable.
undated_award <- list(year = NA_integer_, distance = 70000, complete = TRUE)
stopifnot(training_classify(undated_award$distance, 1L, undated_award$complete) == "never_nearby")
stopifnot(identical(training_decade(1855:1859, "standard_decade"), rep(1850L, 5)))
stopifnot(identical(training_decade(1855:1859, "alternative_decade"), c(1850L, 1850L, 1860L, 1860L, 1860L)))
stopifnot(identical(training_rate(c(0, 1, 1), c(100, NA, 0)), c(0, NA_real_, NA_real_)))
stopifnot(training_rate(2, 1000) + training_rate(3, 1000) + training_rate(4, 1000) == training_rate(9, 1000))
stopifnot(training_contaminated("See previous edition; b Boston") && !training_contaminated("b Boston; see previous edition"))
stopifnot(identical(training_geoid(c("1001", "06075", "")), c("01001", "06075", NA_character_)))
toy <- list(egt = c(-10, 0, 10), att.egt = c(1, 2, 4),
            inf.function = list(dynamic.inf.func.e = matrix(c(1, 2, 2, 3, 3, 5), 2, 3)))
renorm <- training_renormalize(toy)
stopifnot(identical(renorm$estimate, c(-1, 0, 2)), renorm$se[2] == 0)
cat("18 training classification, timing, denominator, contamination and influence-function checks passed.\n")
