args <- commandArgs(trailingOnly = FALSE)
script <- sub("^--file=", "", args[grepl("^--file=", args)])
repo_root <- if (length(script)) normalizePath(file.path(dirname(script), "../.."), winslash = "/") else Sys.getenv("GTL_REPO", getwd())
source(file.path(repo_root, "paths.R"))
suppressPackageStartupMessages(library(data.table))
source(file.path(repo_root, "prep", "mandatory_schooling", "matching_covariate_helpers.R"))
x <- build_matching_covariates(TALENT_DETS_DATA_DIR)
out <- file.path(TALENT_DETS_DATA_DIR, "output", "mandatory_schooling", "matching")
dir.create(out, recursive = TRUE, showWarnings = FALSE)
fwrite(x$panel, file.path(out, "county_matching_covariates.csv"))
fwrite(x$manifest, file.path(out, "variable_manifest.csv"))
fwrite(x$geography_audit, file.path(out, "geography_audit.csv"))
fwrite(x$cmf_geography_audit, file.path(out, "cmf_geography_audit.csv"))
coverage <- x$panel[, lapply(.SD, function(v) sum(is.finite(v))), by = year, .SDcols = matching_covariates]
fwrite(coverage, file.path(out, "coverage.csv"))
print(coverage)
