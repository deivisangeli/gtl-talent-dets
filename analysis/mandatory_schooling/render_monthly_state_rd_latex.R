# Render existing monthly RD exports; never run estimation or rewrite source figures.
# Rscript analysis/mandatory_schooling/render_monthly_state_rd_latex.R [--tex-only]
options(stringsAsFactors=FALSE)
suppressPackageStartupMessages(library(data.table))
require_ok <- function(ok,message) if (!isTRUE(ok)) stop(message,call.=FALSE)
arg <- grep('^--file=',commandArgs(FALSE),value=TRUE)
repo <- if (length(arg)) dirname(normalizePath(sub('^--file=','',arg[1]),winslash='/')) else
  Sys.getenv('GTL_REPO',unset=getwd())
while (!file.exists(file.path(repo,'paths.R'))) {
  parent <- dirname(repo)
  require_ok(parent!=repo,'Cannot locate paths.R; set GTL_REPO.')
  repo <- parent
}
repo <- normalizePath(repo,winslash='/')
config <- new.env(parent=baseenv())
sys.source(file.path(repo,'paths.R'),envir=config)
results <- file.path(config$TALENT_DETS_DATA_DIR,
  'results/mandatory_schooling/compulsory_schooling_amws_monthly_rd')
require_ok(dir.exists(results),'Set TALENT_DETS_DATA_DIR to the Dropbox root containing monthly RD results.')
results <- normalizePath(results,winslash='/')
cli <- commandArgs(TRUE)
require_ok(!length(cli) || identical(cli,'--tex-only'),'Only optional argument is --tex-only.')
stem <- 'monthly_state_rd_figures'
tex_path <- file.path(results,paste0(stem,'.tex'))
pdf_path <- file.path(results,paste0(stem,'.pdf'))
scratch <- file.path(repo,'tmp/pdfs/monthly_state_rd')
dir.create(scratch,recursive=TRUE,showWarnings=FALSE)

# Hash the pre-existing result files, including estimates and every original plot.
protected <- list.files(results,full.names=TRUE,recursive=TRUE)
protected <- protected[!startsWith(basename(protected),paste0(stem,'.'))]
before <- unname(tools::md5sum(protected))
read_result <- function(name) fread(file.path(results,name),colClasses=c(state_fips='character'))
estimates <- read_result('primary_state_estimates.csv')
coverage <- read_result('all_state_dispositions.csv')
inventory <- read_result('cutoff_inventory.csv')
estimated <- estimates[status=='estimated']
setorder(estimated,state)
setorder(coverage,state)
require_ok(nrow(coverage)==51L && !anyDuplicated(coverage$state_fips),'Expected 51 unique jurisdiction dispositions.')
require_ok(nrow(estimated)==34L && !anyDuplicated(estimated$state_fips),'Expected 34 primary state estimates.')
require_ok(all(estimated$source=='combined' & estimated$bandwidth_months==72L & estimated$hac_lag==12L),
  'Not the combined six-year HAC-12 primary specification.')
require_ok(sum(estimated$precision=='verified_monthly')==3L &&
  sum(estimated$precision=='annual_approximation')==31L,'Unexpected precision groups.')
require_ok(sum(coverage$status=='no_balanced_counties')==15L &&
  sum(coverage$status=='outside_monthly_panel')==2L,'Unexpected exclusion groups.')
require_ok(setequal(estimated$state_fips,coverage[status=='estimated',state_fips]),'Estimate/coverage mismatch.')
require_ok(all(is.finite(estimated$estimate) & is.finite(estimated$ci_low) & is.finite(estimated$ci_high)),
  'Missing estimate or confidence interval.')
require_ok(!anyNA(match(coverage$state_fips,inventory$state_fips)),'Missing legal inventory rows.')
coefficient_files <- c('state_comparison_verified_monthly.png','state_comparison_annual_approximation.png')
state_files <- paste0('states/',estimated$state_abbr,'.png')
figure_files <- c(coefficient_files,state_files)
require_ok(all(file.exists(file.path(results,figure_files))),'Missing requested coefficient or state figure.')

escape_tex <- function(x) vapply(as.character(x),function(value) {
  chars <- strsplit(value,'',fixed=TRUE)[[1L]]
  replacements <- c('\\'='\\textbackslash{}','&'='\\&','%'='\\%','$'='\\$',
    '#'='\\#','_'='\\_','{'='\\{','}'='\\}','~'='\\textasciitilde{}','^'='\\textasciicircum{}')
  mapped <- replacements[chars]
  paste0(ifelse(is.na(mapped),chars,mapped),collapse='')
},character(1L),USE.NAMES=FALSE)
number <- function(x) formatC(x,format='f',digits=4L)
precision_label <- function(x) ifelse(x=='verified_monthly','Sourced monthly timing',
  ifelse(x=='annual_approximation','Annual approximation','Excluded'))
