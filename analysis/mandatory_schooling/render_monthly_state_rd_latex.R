require_ok(sum(grepl('\\includegraphics[',out,fixed=TRUE))==36L,'Expected 36 figure references.')
for (file in figure_files) require_ok(sum(grepl(paste0('{',file,'}'),out,fixed=TRUE))==1L,
  paste('Figure does not occur exactly once:',file))
for (caption in captions) require_ok(sum(grepl(paste0('\\captionof{figure}{',caption,'}'),out,fixed=TRUE))==1L,
  'Missing or duplicated estimate caption.')
writeLines(out,tex_path,useBytes=TRUE)
if (!identical(cli,'--tex-only')) {
  compiler <- Sys.which('pdflatex')
  require_ok(nzchar(compiler),paste('pdflatex unavailable; editable source preserved:',tex_path))
  oldwd <- getwd(); setwd(results)
  compile_args <- c('--disable-installer','-halt-on-error','-interaction=nonstopmode',
    '-no-shell-escape','-file-line-error','-recorder',
    paste0('-output-directory=',shQuote(scratch)),shQuote(basename(tex_path)))
  for (pass in 1:2) {
    log <- system2(compiler,compile_args,stdout=TRUE,stderr=TRUE)
    writeLines(log,file.path(scratch,paste0('compile_pass_',pass,'.txt')))
    require_ok(is.null(attr(log,'status')) || attr(log,'status')==0L,
      paste('Compilation failed; source preserved. Inspect',file.path(scratch,paste0('compile_pass_',pass,'.txt'))))
  }
  setwd(oldwd)
  tex_log <- readLines(file.path(scratch,paste0(stem,'.log')),warn=FALSE)
  require_ok(!any(grepl('Overfull|Undefined control sequence|LaTeX Error|undefined references',tex_log)),
    'LaTeX has overflow or unresolved errors; inspect its log.')
  require_ok(file.exists(file.path(scratch,paste0(stem,'.pdf'))),'Compiler produced no PDF.')
  require_ok(file.copy(file.path(scratch,paste0(stem,'.pdf')),pdf_path,overwrite=TRUE),'Could not save PDF.')
}
after <- unname(tools::md5sum(protected))
require_ok(identical(before,after),'An existing source result changed during rendering.')
fwrite(data.table(check=c('34_state_plots','two_coefficient_figures','51_jurisdictions',
  'caption_metadata','each_figure_once','existing_result_hashes'),passed=TRUE),
  file.path(scratch,'validation_checks.csv'))
message('Created ',tex_path)
if (!identical(cli,'--tex-only')) message('Compiled ',pdf_path)
