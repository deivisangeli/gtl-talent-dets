captions <- character(nrow(estimated))
for (i in seq_len(nrow(estimated))) {
  d <- estimated[i]
  if (i %% 2L==1L) out <- c(out,'\\clearpage','\\markright{Monthly AMWS RDs: state plots}')
  captions[i] <- sprintf('%s. Birth-cohort cutoff: %s; %s. Jump: %s; 95\\%% CI [%s, %s] AMWS per 1,000 estimated births.',
    escape_tex(d$state),escape_tex(d$cutoff_date),tolower(precision_label(d$precision)),
    number(d$estimate),number(d$ci_low),number(d$ci_high))
  out <- c(out,'\\begin{minipage}[t][0.475\\textheight][t]{\\textwidth}',
    '\\centering',sprintf('\\includegraphics[width=\\linewidth,height=0.415\\textheight,keepaspectratio]{%s}',state_files[i]),
    paste0('\\captionof{figure}{',captions[i],'}'),
    paste0('\\label{fig:monthly-rd-state-',d$state_abbr,'}'),
    '\\end{minipage}\\par')
  if (i %% 2L==1L) out <- c(out,'\\vspace{0.02\\textheight}')
